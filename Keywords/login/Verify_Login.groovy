class Verify_Login {
	@Keyword
	def VerifyErrorMessage(String expected) {
		TestObject lblError = findTestObject('Object Repository/Login/ErrorMessage_Text')

		Mobile.waitForElementPresent(lblError, GlobalVariable.timeout)

		String actual = Mobile.getText(lblError, GlobalVariable.timeout)

		if (actual != null && actual.contains(expected)) {
			KeywordUtil.markPassed("Pesan error sesuai: '${actual}'")
		} else {
			KeywordUtil.markFailed("Pesan error tidak sesuai. Expected mengandung: '${expected}', Actual: '${actual}'")
		}
	}
}